import { Tool } from '@/types/learning';

export type ResourceTool = Tool | 'forms' | 'immersive' | 'digital';

/** Groups on the Digital resources tab (resources that are not one of the Big 4 tools). */
export type DigitalCategory = 'Logging on and IT help' | 'Planning and scaffolding' | 'Feedback';

